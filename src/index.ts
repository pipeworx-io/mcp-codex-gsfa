interface McpToolDefinition {
  name: string;
  description: string;
  /** Human-facing one-liner (fleet #1967). Optional; consumers fall back to
   *  description. Kept in step with shared/src/types.ts — scripts/lib/
   *  check-inlined-types.mjs reports drift at publish time. */
  summary?: string;
  inputSchema: {
    type: 'object';
    properties: Record<string, unknown>;
    required?: string[];
    anyOf?: Array<{ required: string[] }>;
    oneOf?: Array<{ required: string[] }>;
    allOf?: Array<{ required: string[] }>;
  };
  outputSchema?: Record<string, unknown>;
}

interface McpToolExport {
  tools: McpToolDefinition[];
  callTool: (name: string, args: Record<string, unknown>) => Promise<unknown>;
  meter?: { credits: number };
  cost?: Record<string, unknown>;
  provider?: string;
}

/**
 * Codex GSFA — the FAO/WHO General Standard for Food Additives (CXS 192-1995).
 *
 * Which additives may be used in which foods, at what maximum level, under
 * which notes. Data ships in `data.ts` (generated by scripts/ingest-gsfa.ts
 * from Internet Archive snapshots, because FAO fronts GSFA Online with a
 * Cloudflare challenge). Route + freshness plan: docs/codex-gsfa-plan.md
 *
 * TWO KINDS OF PERMISSION, and the difference is the whole standard:
 *   Table 1 & 2 — a specific maximum level (numeric, or GMP) with notes.
 *   Table 3     — permitted under Good Manufacturing Practice, no numeric cap.
 * Every provision says which it came from. Never merge them.
 *
 * SUBCATEGORY INHERITANCE: a provision on 01.4 also applies to 01.4.4 — the
 * standard says so explicitly. Lookups walk up the numbering, and say when a
 * match was inherited rather than stated directly, because "allowed at 10,000
 * mg/kg" and "allowed because its parent category is" are different answers.
 */

import { GSFA_RAW } from './data.js';

interface RawProvision { t: 1 | 3; cat: string | null; lvl: string | null; n?: number[] }
interface RawAdditive {
  id: number | null;
  ins: string | null;
  name: string | null;
  synonyms: string[];
  functional_classes: string[];
  cac_session: number | null;
  cac_year: number | null;
  snapshot_date: string | null;
  source_path: string | null;
  table3_note: string | null;
  provisions: RawProvision[];
}
interface RawCategory { id: number | null; number: string; name: string }
interface GsfaData {
  source: string;
  cac_sessions_present: number[];
  counts: { additives: number; categories: number; provisions: number; notes: number };
  /** note id (as string) -> note text. */
  notes: Record<string, string>;
  unresolved_additive_ids: number[];
  categories: RawCategory[];
  additives: RawAdditive[];
}

const DATA: GsfaData = JSON.parse(GSFA_RAW);

const CATEGORY_BY_NUMBER = new Map(DATA.categories.map((c) => [c.number, c]));

const norm = (s: string) => s.toLowerCase().replace(/\s+/g, ' ').trim();

/**
 * Categories are derived from the provisions that reference them, so a parent
 * with no provisions of its own never appears — we hold 13.1.1/13.1.2/13.1.3
 * but not 13.1, even though 13.1 (Infant formulae) is a real Codex category.
 * Saying "not in the GSFA category system" for those was wrong and would talk a
 * caller out of a category that genuinely exists. Track them separately so we
 * can say the true thing: we have no provisions referencing it.
 */
const KNOWN_PARENTS = new Set<string>();
for (const c of DATA.categories) {
  const parts = c.number.split('.');
  for (let i = 1; i < parts.length; i++) {
    const parent = parts.slice(0, i).join('.');
    if (!CATEGORY_BY_NUMBER.has(parent)) KNOWN_PARENTS.add(parent);
  }
}

const looksLikeCategoryNumber = (s: string) => /^\d{1,2}(\.\d+)*$/.test(s.trim());

/** Categories at or beneath `num` that actually carry provisions. */
function descendantsWithProvisions(num: string): RawCategory[] {
  const prefix = `${num}.`;
  return DATA.categories.filter((c) => c.number.startsWith(prefix));
}

/**
 * Callers say "complementary foods for infants" far more often than "13.2", and
 * a number-only tool turns that into a dead end (the router asked 13.1 for a
 * question whose own words name 13.2). Accept either.
 */
function resolveCategory(input: string): { number: string | null; matches: RawCategory[] } {
  const raw = String(input ?? '').trim();
  if (!raw) return { number: null, matches: [] };
  if (looksLikeCategoryNumber(raw)) return { number: raw, matches: [] };
  const q = norm(raw);
  const exact = DATA.categories.filter((c) => norm(c.name) === q);
  const hits = exact.length ? exact : DATA.categories.filter((c) => norm(c.name).includes(q));
  return { number: hits.length ? hits[0].number : null, matches: hits };
}

/** "01.4.4" -> ["01.4.4", "01.4", "01"] — provisions inherit down the tree. */
function categoryChain(num: string): string[] {
  const parts = num.split('.');
  const out: string[] = [];
  for (let i = parts.length; i > 0; i--) out.push(parts.slice(0, i).join('.'));
  return out;
}

function freshness(a: RawAdditive) {
  return {
    cac_session: a.cac_session,
    cac_year: a.cac_year,
    snapshot_date: a.snapshot_date,
    source_path: a.source_path,
  };
}

/**
 * Note text is inlined rather than left as an id to look up. A provision is not
 * fully specified without its notes — "GMP" and "GMP, ready-to-drink products
 * only" are different permissions — so making the caller fetch them separately
 * invites them to read the level and stop.
 */
function shapeProvision(p: RawProvision) {
  const ids = p.n ?? [];
  return {
    provision_table: p.t === 3 ? ('table3' as const) : ('table1_2' as const),
    food_category: p.cat,
    food_category_name: p.cat ? (CATEGORY_BY_NUMBER.get(p.cat)?.name ?? null) : null,
    max_level: p.lvl,
    note_ids: ids,
    notes: ids.map((id) => ({ id, text: DATA.notes[String(id)] ?? null })),
  };
}

function shapeAdditive(a: RawAdditive) {
  return {
    ins: a.ins,
    name: a.name,
    synonyms: a.synonyms,
    functional_classes: a.functional_classes,
    ...freshness(a),
  };
}

/** Match on INS, exact name, synonym, then substring — most precise first. */
function findAdditives(query: string): RawAdditive[] {
  const q = norm(query);
  const qIns = q.replace(/^ins\s*/, '').replace(/^e/, '');
  const exact = DATA.additives.filter(
    (a) => (a.ins && norm(a.ins) === qIns) || (a.name && norm(a.name) === q) || a.synonyms.some((s) => norm(s) === q),
  );
  if (exact.length) return exact;
  return DATA.additives.filter(
    (a) =>
      (a.name && norm(a.name).includes(q)) ||
      a.synonyms.some((s) => norm(s).includes(q)) ||
      (a.ins && norm(a.ins).startsWith(qIns)),
  );
}

