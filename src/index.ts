async function callTool(name: string, args: Record<string, unknown>): Promise<unknown> {
  const limitOf = (d: number) => {
    const n = Number(args.limit);
    return Number.isFinite(n) && n > 0 ? Math.min(n, 1000) : d;
  };

  switch (name) {
    case 'gsfa_check_use': {
      const matches = findAdditives(String(args.additive ?? ''));
      if (!matches.length) {
        return { found: false, reason: 'additive_not_found', additive_requested: args.additive, hint: NOT_FOUND_HINT };
      }
      const a = matches[0];
      const asked = String(args.food_category ?? '').trim();
      const resolved = resolveCategory(asked);
      if (!resolved.number) {
        return {
          found: true,
          permitted: null,
          reason: 'food_category_unresolved',
          additive: shapeAdditive(a),
          food_category_requested: asked,
          hint: 'Give a GSFA category number (e.g. "13.2") or a name that matches one. Browse with gsfa_search_food_categories.',
        };
      }
      const wanted = resolved.number;
      const chain = categoryChain(wanted);
      // Nearest match wins: an exact provision beats an inherited one.
      for (const cat of chain) {
        const hits = a.provisions.filter((p) => p.cat === cat);
        if (!hits.length) continue;
        return {
          found: true,
          permitted: true,
          additive: shapeAdditive(a),
          food_category_requested: asked,
          resolved_food_category: wanted,
          matched_food_category: cat,
          inherited_from_parent: cat !== wanted,
          provisions: hits.map(shapeProvision),
          ...(a.table3_note ? { table3_note: a.table3_note } : {}),
        };
      }
      // A parent category we hold no provisions for is the case most likely to
      // mislead: the caller asked 13.1, which exists, and the useful answer is
      // that its subcategories are where the provisions live.
      const kids = descendantsWithProvisions(wanted).filter((c) =>
        a.provisions.some((p) => p.cat === c.number),
      );
      return {
        found: true,
        permitted: false,
        additive: shapeAdditive(a),
        food_category_requested: asked,
        resolved_food_category: wanted,
        categories_checked: chain,
        ...(kids.length
          ? { subcategories_with_provisions: kids.map((c) => ({ food_category: c.number, name: c.name })) }
          : {}),
        hint: kids.length
          ? `No provision for this additive at ${wanted} itself, but ${kids.length} subcategor${kids.length === 1 ? 'y has' : 'ies have'} one — a GSFA provision applies downward, not upward, so check those directly.`
          : CATEGORY_BY_NUMBER.has(wanted) || KNOWN_PARENTS.has(wanted)
            ? 'No GSFA provision for this additive in that category or any parent. Absence here means the standard lists no provision, which is not the same as an explicit prohibition.'
            : `No provision in this dataset references food category "${wanted}". That does not mean the category is absent from the Codex system — this dataset only holds categories some provision names. Browse with gsfa_search_food_categories.`,
      };
    }

    case 'gsfa_search_additive': {
      const matches = findAdditives(String(args.query ?? ''));
      if (!matches.length) {
        return { found: false, reason: 'no_match', query: args.query, hint: NOT_FOUND_HINT };
      }
      return {
        found: true,
        count: matches.length,
        additives: matches.slice(0, limitOf(20)).map((a) => ({
          ...shapeAdditive(a),
          provision_counts: {
            table1_2: a.provisions.filter((p) => p.t === 1).length,
            table3: a.provisions.filter((p) => p.t === 3).length,
          },
        })),
      };
    }

    case 'gsfa_additive_provisions': {
      const matches = findAdditives(String(args.additive ?? ''));
      if (!matches.length) {
        return { found: false, reason: 'additive_not_found', additive_requested: args.additive, hint: NOT_FOUND_HINT };
      }
      const a = matches[0];
      const filter = typeof args.table === 'string' ? args.table : null;
      let provs = a.provisions;
      if (filter === 'table1_2') provs = provs.filter((p) => p.t === 1);
      if (filter === 'table3') provs = provs.filter((p) => p.t === 3);
      return {
        found: true,
        additive: shapeAdditive(a),
        total_provisions: provs.length,
        counts: {
          table1_2: a.provisions.filter((p) => p.t === 1).length,
          table3: a.provisions.filter((p) => p.t === 3).length,
        },
        ...(a.table3_note ? { table3_note: a.table3_note } : {}),
        provisions: provs.slice(0, limitOf(200)).map(shapeProvision),
      };
    }

    case 'gsfa_food_category_additives': {
      const askedCat = String(args.food_category ?? '').trim();
      const res = resolveCategory(askedCat);
      if (!res.number) {
        return {
          found: false,
          reason: 'food_category_unresolved',
          food_category_requested: askedCat,
          hint: 'Give a GSFA category number (e.g. "14.1.5") or a name that matches one. Browse with gsfa_search_food_categories.',
        };
      }
      const wanted = res.number;
      const inherit = args.include_inherited !== false;
      const chain = inherit ? categoryChain(wanted) : [wanted];
      const out: unknown[] = [];
      for (const a of DATA.additives) {
        for (const p of a.provisions) {
          if (!p.cat || !chain.includes(p.cat)) continue;
          out.push({
            ins: a.ins,
            name: a.name,
            ...shapeProvision(p),
            inherited_from_parent: p.cat !== wanted,
          });
        }
      }
      if (!out.length) {
        const kids = descendantsWithProvisions(wanted);
        return {
          found: false,
          reason: CATEGORY_BY_NUMBER.has(wanted) || KNOWN_PARENTS.has(wanted) ? 'no_provisions' : 'category_not_referenced',
          food_category_requested: askedCat,
          resolved_food_category: wanted,
          ...(kids.length
            ? { subcategories_with_provisions: kids.slice(0, 20).map((c) => ({ food_category: c.number, name: c.name })) }
            : {}),
          hint: kids.length
            ? `No provisions at ${wanted} itself; its subcategories carry them. GSFA provisions apply downward, so query those.`
            : 'No provision in this dataset references that category. Browse with gsfa_search_food_categories.',
        };
      }
      return {
        found: true,
        food_category: wanted,
        food_category_requested: askedCat,
        food_category_name: CATEGORY_BY_NUMBER.get(wanted)?.name ?? null,
        categories_included: chain,
        count: out.length,
        additives: out.slice(0, limitOf(200)),
      };
    }

    case 'gsfa_search_food_categories': {
      const q = norm(String(args.query ?? ''));
      const hits = DATA.categories.filter((c) => c.number.startsWith(q) || norm(c.name).includes(q));
      if (!hits.length) {
        return { found: false, reason: 'no_match', query: args.query, hint: 'Try a broader word such as "cheese" or a number prefix such as "01".' };
      }
      return {
        found: true,
        count: hits.length,
        categories: hits.slice(0, limitOf(50)).map((c) => ({ food_category: c.number, name: c.name })),
      };
    }

    case 'gsfa_notes': {
      const ids = Array.isArray(args.note_ids) ? args.note_ids.map(Number).filter(Number.isFinite) : [];
      if (ids.length) {
        return {
          found: true,
          notes: ids.map((id) => ({ id, text: DATA.notes[String(id)] ?? null })),
          unresolved: ids.filter((id) => !DATA.notes[String(id)]),
        };
      }
      const q = norm(String(args.query ?? ''));
      if (!q) {
        return {
          found: false,
          reason: 'no_input',
          hint: 'Pass note_ids to resolve specific notes, or query to search note wording.',
          total_notes: Object.keys(DATA.notes).length,
        };
      }
      const hits = Object.entries(DATA.notes).filter(([, text]) => norm(text).includes(q));
      if (!hits.length) {
        return { found: false, reason: 'no_match', query: args.query, hint: 'Try a shorter phrase, e.g. "fat basis" or "ready-to-drink".' };
      }
      const n = Number(args.limit);
      const lim = Number.isFinite(n) && n > 0 ? Math.min(n, 500) : 25;
      return {
        found: true,
        count: hits.length,
        notes: hits.slice(0, lim).map(([id, text]) => ({ id: Number(id), text })),
      };
    }

    case 'gsfa_coverage':
      return {
        found: true,
        source: DATA.source,
        standard: 'Codex General Standard for Food Additives (CXS 192-1995)',
        cac_sessions_present: DATA.cac_sessions_present,
        counts: DATA.counts,
        unresolved_additive_ids: DATA.unresolved_additive_ids,
        caveat:
          'Records are read from archived snapshots of GSFA Online, so individual additives can lag the newest Codex session — each result carries its own cac_session and snapshot_date. Unresolved ids are entries whose every archived snapshot is one of FAO\'s own error pages.',
      };

    default:
      throw new Error(`Unknown tool: ${name}`);
  }
}

export default { tools, callTool, meter: { credits: 1 } } satisfies McpToolExport;
